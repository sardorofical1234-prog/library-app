CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    isbn VARCHAR(255) NOT NULL UNIQUE,
    published_year INTEGER,
    total_copies INTEGER NOT NULL,
    available_copies INTEGER NOT NULL,
    CONSTRAINT ck_books_total_copies CHECK (total_copies >= 1),
    CONSTRAINT ck_books_available_copies CHECK (
        available_copies >= 0 AND available_copies <= total_copies
    )
);

CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    loan_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE
);

CREATE INDEX idx_loans_user_loan_date ON loans(user_id, loan_date DESC);
CREATE INDEX idx_loans_book_id ON loans(book_id);
CREATE INDEX idx_loans_active_due_date ON loans(due_date) WHERE return_date IS NULL;
